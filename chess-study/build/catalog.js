#!/usr/bin/env node

const fs   = require('fs');
const path = require('path');

const { load: loadComponents } = require('./components');
const { validateProps }        = require('./props');
const { esc }                  = require('./template');

const ROOT = path.join(__dirname, '..');

function requireMetadata(component) {
  const { meta, file } = component;
  const missing = [];
  if (!meta.purpose)            missing.push('meta.purpose');
  if (!meta.props)              missing.push('meta.props');
  if (!meta.demo)               missing.push('meta.demo');
  if (missing.length) {
    throw new Error(`${file}: missing ${missing.join(', ')} — every component must be documentable and demonstrable`);
  }
}

// A pipe splits the markdown row — `callout`'s purpose contains "note | warn | danger".
const cell = s => String(s).replace(/\|/g, '\\|');

function propSignature(props) {
  return Object.entries(props)
    .map(([name, type]) => `${name}: ${type}`)
    .join(', ');
}

function renderRegistry(components) {
  const rows = [...components.values()].map(c =>
    `| \`${c.meta.name}\` | ${cell(c.meta.purpose)} | \`${cell(propSignature(c.meta.props))}\` | ${c.tier} |`
  ).join('\n');

  const local = [...components.values()].filter(c => c.tier === 'local');

  return `<!-- GENERATED by build/catalog.js — do not edit.
     Every row comes from a component's own meta. Add a component under
     components/local/ and it appears here on the next \`make catalog\`. -->

# Component vocabulary

The components a lesson's \`.json\` may name. Anything outside this list fails the
build, which is what keeps the vocabulary meaningful rather than a suggestion.

| Component | Purpose | Props | Tier |
|---|---|---|---|
${rows}

**${components.size} components** — ${components.size - local.length} core, ${local.length} local.

\`core/\` is upstream's. \`local/\` belongs to this fork and wins on a name
collision, so a component can be overridden without editing an upstream file.

Every component is rendered from its own \`meta.demo\` in
[\`sandbox/components.html\`](sandbox/components.html); run \`make catalog\` and open
it to see the whole vocabulary on one page.
`;
}

function renderGallery(components) {
  const items = [];
  const failures = [];

  for (const c of components.values()) {
    const problems = validateProps(c, c.meta.demo).filter(p => p.level === 'error');
    if (problems.length) {
      failures.push(`${c.file}: meta.demo does not satisfy meta.props — ${problems.map(p => p.message).join('; ')}`);
      continue;
    }

    let html;
    try {
      html = c.render(c.meta.demo, { children: '<div class="lx-prose"><p>Sample content inside this component.</p></div>' });
    } catch (err) {
      failures.push(`${c.file}: threw while rendering its own demo — ${err.message}`);
      continue;
    }

    items.push(`
  <section class="cat-item" id="c-${esc(c.meta.name)}">
    <div class="cat-head">
      <h2 class="lx-h2">${esc(c.meta.name)}</h2>
      <span class="lx-badge">${esc(c.tier)}</span>
    </div>
    <p class="lx-muted">${esc(c.meta.purpose)}</p>
    <p class="cat-props"><code>${esc(propSignature(c.meta.props))}</code></p>
    <div class="cat-demo">
${html}
    </div>
  </section>`);
  }

  if (failures.length) {
    const err = new Error('component demos failed:\n  ' + failures.join('\n  '));
    err.failures = failures;
    throw err;
  }

  const index = [...components.values()]
    .map(c => `<a class="lx-btn lx-btn--outline" href="#c-${esc(c.meta.name)}">${esc(c.meta.name)}</a>`)
    .join('\n      ');

  return `<!DOCTYPE html>
<!-- GENERATED by build/catalog.js — do not edit.
     Each block below is a component rendering its own meta.demo. -->
<html lang="en">
<head>
<meta charset="UTF-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>learno — components</title>
<link rel="stylesheet" href="/assets/learno.css" />
<link rel="stylesheet" href="/assets/components.css" />
<style>
  .cat-item + .cat-item { margin-top: 3rem; padding-top: 2rem; border-top: 1px solid var(--lx-border); }
  .cat-head { display: flex; align-items: center; gap: .6rem; }
  .cat-props { margin: .4rem 0 1rem; }
  .cat-props code {
    font-family: ui-monospace, SFMono-Regular, Menlo, monospace;
    font-size: .75rem; color: var(--lx-text-muted);
  }
  .cat-index { display: flex; flex-wrap: wrap; gap: .4rem; margin-bottom: 2.5rem; }
  .cat-index .lx-btn { padding: .3rem .6rem; font-size: .8rem; }
  .cat-demo > * + * { margin-top: 1.5rem; }
</style>
</head>
<body class="lx-shell">


<svg class="lx-defs" aria-hidden="true">
  <defs>
    <marker id="lx-arrow" viewBox="0 0 10 10" refX="9" refY="5"
            markerWidth="6" markerHeight="6" orient="auto-start-reverse">
      <path class="lx-arrowhead" d="M 0 0 L 10 5 L 0 10 z" />
    </marker>
  </defs>
</svg>

<div class="lx-wrap">
  <header class="lx-lesson-head">
    <span class="lx-badge">generated</span>
    <h1 class="lx-title">Components</h1>
    <p class="lx-subtitle">
      Every component in the vocabulary, rendered from its own
      <code>meta.demo</code>. This page is not written by hand — it goes and comes back with
      <code>make catalog</code>.
    </p>
  </header>

  <nav class="cat-index">
      ${index}
  </nav>
${items.join('\n')}
</div>

<script type="application/json" id="lx-config">{"lesson":"components-gallery","concepts":[],"phases":[]}</script>
<script src="/assets/learno.js" defer></script>
</body>
</html>
`;
}

function main() {
  const components = loadComponents();

  for (const c of components.values()) requireMetadata(c);

  const registryPath = path.join(ROOT, 'COMPONENTS.md');
  fs.writeFileSync(registryPath, renderRegistry(components));
  console.log(`  COMPONENTS.md            ${components.size} components`);

  const galleryPath = path.join(ROOT, 'sandbox', 'components.html');
  const gallery = renderGallery(components);
  fs.writeFileSync(galleryPath, gallery);
  console.log(`  sandbox/components.html  ${(Buffer.byteLength(gallery) / 1024).toFixed(1)}K`);
}

if (require.main === module) {
  try { main(); }
  catch (err) {
    console.error(`\n  error  ${err.message}\n`);
    process.exit(1);
  }
}

module.exports = { renderRegistry, renderGallery, requireMetadata };
