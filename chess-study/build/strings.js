let lang = null;

function language() {
  if (lang) return lang;
  try {
    const cfg = JSON.parse(fs.readFileSync(path.join(ROOT, 'learno.json'), 'utf8'));
    lang = STRINGS[cfg.lang] ? cfg.lang : DEFAULT_LANG;
  } catch {
    lang = DEFAULT_LANG;
  }
  return lang;
}

function table(lang) {
  return { ...STRINGS[DEFAULT_LANG], ...STRINGS[lang] };
}

function t(key) {
  return table(language())[key] ?? key;
}

function runtimeStrings() {
  const out = {};
  for (const key of Object.keys(STRINGS[DEFAULT_LANG])) {
    if (/^(score|run|mic|recall\.(ok|bad))/.test(key)) out[key] = t(key);
  }
  return out;
}

module.exports = { t, table, language, runtimeStrings, STRINGS, DEFAULT_LANG };
